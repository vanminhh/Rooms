test('VIEW-08: exact hours are Hanoi instants; legacy retains its broad slot', () => {
  const time = mod('features/viewings/time.ts')
  assert.equal(time.hourInstant('2026-11-16', 8), '2026-11-16T01:00:00.000Z')
  assert.equal(time.hourInstant('2026-11-16', 19), '2026-11-16T12:00:00.000Z')
  assert.equal(time.viewingDay({ visitAt: '2026-11-15T18:00:00Z', visitDate: null }), '2026-11-16')
  assert.equal(time.viewingStart({ visitAt: null, visitDate: '2026-11-16', timeSlot: 'AFTERNOON' }), Date.parse('2026-11-16T07:00:00Z'))
  assert.match(time.viewingTime({ visitAt: null, visitDate: '2026-11-16', timeSlot: 'MORNING' }, 'en'), /Morning/)
  assert.match(time.viewingTime({ visitAt: '2026-11-16T03:00:00Z' }, 'en'), /10:00/)
})
test('VIEW-01/18/20/21: account API routes and bodies; availability never sends identity', async () => {
  const raw = fakeFetch([{ prefix: '/public/rooms/7/viewing-times', handler: () => ok([]) }, { prefix: '/me/rooms/7/viewing-times', handler: () => ok([]) }, { prefix: '/', handler: () => ok([], { page: 2, limit: 20, total: 0 }) }])
  const calls = new Proxy([], { get: (_, index) => raw[index] && ({ ...raw[index], path: raw[index].url.replace('/api/v1', ''), body: raw[index].body ? JSON.parse(raw[index].body) : undefined }) })
  const api = mod('features/viewings/api.ts')
  await api.getViewingTimes(7, '2026-11-15', '2026-12-15', false)
  await api.getViewingTimes(7, '2026-11-15', '2026-12-15', true)
  await api.bookViewing({ roomId: 7, visitAt: '2026-11-16T03:00:00.000Z', note: 'nội dung giữ nguyên', guestPhone: 'forged' })
  await api.listOwnViewings(2)
  await api.getOwnViewing(8)
  await api.cancelOwnViewing(8)
  assert.match(calls[0].path, /^\/public\/rooms\/7\/viewing-times\?from=2026-11-15&to=2026-12-15$/)
  assert.match(calls[1].path, /^\/me\/rooms\/7\/viewing-times\?/)
  assert.deepEqual(calls[2].body, { roomId: 7, visitAt: '2026-11-16T03:00:00.000Z', note: 'nội dung giữ nguyên' })
  assert.equal(calls[3].path, '/me/viewings?page=2&limit=20')
  assert.equal(calls[4].path, '/me/viewings/8')
  assert.equal(calls[5].path, '/me/viewings/8/cancel')
})
test('VIEW-03/09/15: staff uses exact hour and confirmation action endpoint', async () => {
  const raw = fakeFetch([{ prefix: '/', handler: () => ok({}) }])
  const calls = new Proxy([], { get: (_, index) => raw[index] && ({ ...raw[index], path: raw[index].url.replace('/api/v1', ''), body: raw[index].body ? JSON.parse(raw[index].body) : undefined }) })
  const api = mod('features/viewings/api.ts')
  await api.createViewing({ roomId: 7, guestName: 'Khách', guestPhone: '0900000005', visitAt: '2026-11-16T03:00:00Z' })
  await api.updateViewing(8, { visitAt: '2026-11-16T04:00:00Z', status: 'CANCELLED', note: 'Khách bận' })
  await api.confirmViewing(8, 'PHONE'); await api.confirmViewing(8, 'EMAIL')
  assert.equal(calls[0].body.visitAt, '2026-11-16T03:00:00Z')
  assert.equal('visitDate' in calls[0].body, false)
  assert.deepEqual(calls[1].body, { visitAt: '2026-11-16T04:00:00Z', status: 'CANCELLED', note: 'Khách bận' })
  assert.equal(calls[2].path, '/viewings/8/confirm')
  assert.deepEqual(calls[2].body, { via: 'PHONE' }); assert.deepEqual(calls[3].body, { via: 'EMAIL' })
})
